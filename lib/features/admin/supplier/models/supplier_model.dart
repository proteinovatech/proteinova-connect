class Supplier {
  final String name;
  final String id;
  final String location;
  final String owner;
  final String phone;
  final String email;
  final bool active;

  Supplier({
    required this.name,
    required this.id,
    required this.location,
    required this.owner,
    required this.phone,
    required this.email,
    required this.active,
  });
}